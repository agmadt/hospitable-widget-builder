// Refreshes dummy.json, the builder's copy of the sample data, from a Worker
// running in dummy mode, so the builder previews exactly what a Worker serves.
//   node scripts/sync-sample.mjs [worker-url]   (default http://127.0.0.1:8787)

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const worker = (process.argv[2] || 'http://127.0.0.1:8787').replace(/\/+$/, '');
const out = fileURLToPath(new URL('../src/assets/dummy.json', import.meta.url));

async function get(path) {
  const res = await fetch(worker + path);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  if (res.headers.get('X-Hosp-Mode') !== 'dummy') throw new Error('That Worker is not in dummy mode; refusing to copy real data.');
  const body = await res.json();
  delete body.mode;
  delete body.updated_at;
  delete body.status;
  return body;
}

const list = await get('/api/properties');
const sample = { _comment: 'Sample data for the builder preview. Generated by scripts/sync-sample.mjs from a dummy-mode Worker.', generated: new Date().toISOString().slice(0, 10), host: await get('/api/host'), properties: list.properties, data: {} };
for (const p of list.properties) {
  const id = encodeURIComponent(p.id);
  sample.data[p.id] = {
    property: await get(`/api/properties/${id}`),
    calendar: await get(`/api/properties/${id}/calendar`),
    reviews: await get(`/api/properties/${id}/reviews`),
    guide: await get(`/api/properties/${id}/guide`),
  };
}
// A signed-in guest's stay, for the guest widgets: the sample bookings that
// arrive today and in twelve days (see the kit's src/fixtures/dummy.json).
async function stayOf(code, check) {
  const login = await fetch(worker + '/stay/login', { method: 'POST', headers: { Origin: worker, 'Content-Type': 'application/json' }, body: JSON.stringify({ code, check }) });
  if (!login.ok) throw new Error(`/stay/login for ${code}: HTTP ${login.status}`);
  const res = await fetch(worker + '/stay', { headers: { Authorization: `Bearer ${(await login.json()).token}` } });
  if (!res.ok || res.headers.get('X-Hosp-Mode') !== 'dummy') throw new Error(`/stay for ${code}: HTTP ${res.status}`);
  const body = await res.json();
  delete body.mode;
  return body;
}
sample.stays = { arrival: await stayOf('HM4CXJ4KPX', 'Moore'), early: await stayOf('4182736455', 'Becker') };

await writeFile(out, JSON.stringify(sample) + '\n');
console.log(`Wrote ${out} (${list.properties.length} properties)`);
